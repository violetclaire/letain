function actorIdentity(): ActorIdentity {
  return {
    actorId: "blind-evaluation-operator",
    actorType: "agent",
    verifiedIdentity: true,
    operatingOrganization: "Synthetic Blind Evaluation",
    modelProvider: "synthetic",
    delegatedBy: "blind-evaluation-owner",
    identityEvidence: ["blind-session-identity"],
  };
}

function currentConditions(
  environment: string,
  input: BlindCaseInput,
): CurrentConditions {
  return {
    environment,
    activeIncident: input.domain === "incident_response",
    targetState: "synthetic",
    knownAnomalies: [],
    policyVersion: POLICY_VERSION,
    conditionVersion: CONDITION_VERSION,
    evidenceChanged: input.evidenceChanged ?? false,
    permissionRevoked: input.permissionRevoked ?? false,
    velocity: 1,
    recentActionCount: input.recentActionCount ?? 1,
    estimatedBlastRadius: input.estimatedBlastRadius ?? 1,
  };
}

function systemEvidence(input: BlindCaseInput): EvidenceBundle {
  return {
    evidenceId: `${input.caseId}-system-evidence`,
    evidenceType: "SYSTEM",
    source: "blind-independent-observer",
    observedAt: "2026-07-29T17:55:00.000Z",
    confidence: 95,
    freshness: input.evidenceFreshness ?? "current",
    actorControlled: false,
    value: "The named task, target, and environment were independently recorded.",
    supportingAttestations: ["blind-observer-attestation"],
    taskId: input.taskId,
    maximumConsequenceLevel: input.consequenceLevel,
  };
}

function humanApproval(input: BlindCaseInput): HumanApproval | null {
  if (!input.approval) return null;
  return {
    approvalId: `${input.caseId}-approval`,
    approverId: input.approval.approverId,
    authorizedApprover: true,
    actorId: "blind-evaluation-operator",
    taskId: input.taskId,
    exactTool: input.tool,
    exactAction: input.action,
    exactTarget: input.target,
    environment: input.environment,
    approvedAt: "2026-07-29T17:45:00.000Z",
    expiresAt: "2026-07-29T18:30:00.000Z",
    revoked: false,
    conditionVersion: CONDITION_VERSION,
    constraints: input.approval.constraints ?? [],
    rationale: "An authorized human approved this exact synthetic action.",
  };
}

function approvalEvidence(approval: HumanApproval): EvidenceBundle {
  return {
    evidenceId: approval.approvalId,
    evidenceType: "HUMAN_APPROVAL",
    source: approval.approverId,
    observedAt: approval.approvedAt,
    confidence: 100,
    freshness: "current",
    actorControlled: false,
    value: approval.rationale,
    supportingAttestations: ["blind-human-approval-attestation"],
    taskId: approval.taskId,
    humanApproval: approval,
  };
}

function buildCase(input: BlindCaseInput): BlindActionCase {
  const evidence = [systemEvidence(input)];
  const approval = humanApproval(input);
  if (approval) evidence.push(approvalEvidence(approval));

  const request: ActionRequest = {
    requestId: `${input.caseId}-request`,
    actorId: "blind-evaluation-operator",
    actorType: "agent",
    taskId: input.taskId,
    tool: input.tool,
    action: input.action,
    target: input.target,
    environment: input.environment,
    requestedAt: NOW,
    claimedScope: `One exact ${input.action} action on ${input.target}`,
    consequenceLevel: input.consequenceLevel,
    evidenceReferences: evidence.map((item) => item.evidenceId),
    currentConditionReferences: [CONDITION_VERSION],
  };

  const scope: AssignedScope = {
    taskId: input.taskId,
    permittedActions: [...input.permittedActions],
    permittedTools: [...input.permittedTools],
    permittedTargets: [...input.permittedTargets],
    permittedEnvironments: input.permittedEnvironments ?? [input.environment],
    prohibitedActions: [...(input.prohibitedActions ?? [])],
    prohibitedTargets: [...(input.prohibitedTargets ?? [])],
    validFrom: VALID_FROM,
    validUntil: VALID_UNTIL,
    conditionVersion: CONDITION_VERSION,
    maximumConsequenceLevel: input.consequenceLevel,
    requiredHumanApprovals: [...(input.requiredHumanApprovals ?? [])],
    constraints: [...(input.constraints ?? [])],
    maximumRecentActionCount: input.maximumRecentActionCount ?? 20,
    maximumBlastRadius: input.maximumBlastRadius ?? 10,
  };

  const context: EvaluationContext = {
    actor: actorIdentity(),
    scope,
    evidence,
    conditions: currentConditions(input.environment, input),
    authority: BLIND_AUTHORITY,
  };

  return {
    caseId: input.caseId,
    sequence: input.sequence,
    pairId: input.pairId,
    domain: input.domain,
    label: input.label,
    request,
    context,
  };
}

